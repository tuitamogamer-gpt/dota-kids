"""🎬 Animacije moći (v0.56) — svaka moć svakog junaka ima svoju kretnju.

build_models.py za svakog junaka pozove ability_anims(m, id, P) i u GLB uđu isječci
  'abQ' 'abW' 'abE' 'abR'   jednokratna kretnja kad se moć baci (scene3d.js: syncAnim)
  'chQ' … 'chR'             petlja dok se moć kanalizira (Veliki zalogaj, Lepeza strijela, Epicentar)

Pravila (ista kao za 'cast' u build_models.py):
  • učinak moći u igri nastaje ODMAH, pa isječak počinje u zamahu: kadar 0 je napeta poza (igra u nju pretopi
    trenutnu pozu), udarac pada oko 3. kadra, zatim zamah prolazi dalje i tijelo se smiri;
  • skokovi (LEAP_KEYS u scene3d.js) traju 14 kadrova kao 'jump' — igra ih rastegne na trajanje leta:
    odraz 0–2, let 3–9, doskok 11;
  • dijelovi tijela: body, head, armL, armR, legL, legR, tail, wingL, wingR (kojih nema, preskaču se).

Kutovi su u stupnjevima, model gleda u +X, Z je gore:
  ruka  R(out, fwd): out = odmak u stranu, fwd = podizanje naprijed (90 = ravno naprijed, 175 = iznad glave, minus = unatrag)
  noga  R(out, fwd)  isto;  tijelo (nagib u stranu, naprijed +, okret ulijevo +) + pomak (naprijed, lijevo, gore)
  glava (nagib, dolje +, ulijevo +);  rep (0, gore +, mah)

Brza provjera bez pune izgradnje (2 s po junaku):
  python tools/blender/build_models.py --dev-anim --only=vitez,slon --out=/tmp/test.glb
"""
Z = (0, 0, 0)


def R(out=0, fwd=0, roll=0):
    return (-out, -fwd, roll)


def L(out=0, fwd=0, roll=0):
    return (out, -fwd, roll)


LIB = {}


def ab(fn):
    LIB[fn.__name__] = fn
    return fn


def _hands(P, hand=None):
    """(glavna ruka, druga ruka, funkcija kuta glavne, funkcija kuta druge, predznak okreta tijela).
    Puškari drže pušku u desnoj, pa bacaju i pokazuju lijevom."""
    hand = hand or ('L' if P['kind'] == 'rifle' else 'R')
    return ('armR', 'armL', R, L, 1) if hand == 'R' else ('armL', 'armR', L, R, -1)


def _wings(t, keys):
    """krila (zmaj, pčela) prate kretnju: keys = [(kadar, raširenost°)]"""
    t['wingL'] = [(f, (a * 0.55, 0, -a * 0.28)) for f, a in keys]   # pri većem otklonu krila nestanu iza glave
    t['wingR'] = [(f, (-a * 0.55, 0, a * 0.28)) for f, a in keys]


